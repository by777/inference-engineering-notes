/*
 * 验证 Ⅲ.1 的精度表：要求小数点后 d 位时，float 的整数部分最多到多少？
 *
 * 每列给一对值，都必须先存进 float 再打印：
 *   边界内 maxI + frac   ->  %.d f 打印正确
 *   越界  (maxI+1) + frac ->  %.d f 打印错误
 *
 * 原因：越界后进入下一个二进制阶，ulp 翻倍。一旦 ulp > 10^-d，
 *       第 d 位小数就不再可靠。
 */
#include <stdio.h>

#define F(x) ((double)(float)(x)) /* 强制先存成 float，再传给 printf */

int main(void)
{
    puts("列  要求精度    整数上限    边界内 -> 印出     越界 -> 印出      真值应为");
    puts("----------------------------------------------------------------------------------");

    printf("1   %-11s %-10d %-17.1f %-16.1f %.1f\n",
           "0.1", 1048575, F(1048575.1651f), F(1048576.1651f), 1048576.1651);

    printf("2   %-11s %-10d %-17.2f %-16.2f %.2f\n",
           "0.01", 131071, F(131071.00651f), F(131072.00651f), 131072.00651);

    printf("3   %-11s %-10d %-17.3f %-16.3f %.3f\n",
           "0.001", 16383, F(16383.00065f), F(16384.00065f), 16384.00065);

    printf("4   %-11s %-10d %-17.4f %-16.4f %.4f\n",
           "0.0001", 1023, F(1023.0001651f), F(1024.0001651f), 1024.0001651);

    printf("5   %-11s %-10d %-17.5f %-16.5f %.5f\n",
           "0.00001", 127, F(127.0000065f), F(128.0000065f), 128.0000065);

    printf("6   %-11s %-10d %-17.6f %-16.6f %.6f\n",
           "0.000001", 15, F(15.00000065f), F(16.00000065f), 16.00000065);

    printf("7   %-11s %-10d %-17.7f %-16.7f %.7f\n",
           "0.0000001", 0, F(0.000000165f), F(1.000000165f), 1.000000165);
    return 0;
}